const TABLES: Record<Lang, Record<Key, string>> = { vi: VI, en: EN };

let lang: Lang = 'vi';

export function setLang(l: Lang): void {
  lang = l;
}

export function getLang(): Lang {
  return lang;
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return TABLES[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

